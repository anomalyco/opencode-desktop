//! Plugin source origins, manifest validation, folder walking, content hashing, and Luau
//! `Sources` assembly.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use opencode_plugin_spec::{Compat, ContractVersion, Manifest};
use sha2::{Digest, Sha256};

use crate::catalogs::Catalogs;

/// Where a plugin comes from, highest first.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Tier {
    Dev,
    Override,
    Bundled,
    User,
}

impl Tier {
    /// Whether it waits for the user's OK before it first runs: anything that isn't shipped with
    /// the app or named on the command line.
    pub fn needs_trust(self) -> bool {
        matches!(self, Self::Override | Self::User)
    }

    pub fn label(self) -> &'static str {
        match self {
            Self::Dev => "Dev",
            Self::Override => "Override",
            Self::Bundled => "Built-in",
            Self::User => "Installed",
        }
    }
}

/// One plugin's precompiled Luau bytecode modules `(plugin_id, &[(rel_path, bytecode, native)])`.
pub type PrecompiledEntry = (&'static str, &'static [(&'static str, &'static [u8], bool)]);

/// One embedded built-in plugin record `(plugin_id, files, catalog_table)`.
pub type BuiltinEntry<'a> = (&'a str, &'a [(&'a str, &'a str)], &'static [u8]);

/// Precompiled Luau bytecode modules emitted at build time by a host's `build.rs`.
#[derive(Clone, Copy, Debug)]
pub struct PrecompiledModules {
    modules: &'static [PrecompiledEntry],
}

impl PrecompiledModules {
    /// Wraps the static bytecode table generated by a host's `build.rs`.
    ///
    /// # Safety
    /// Every bytecode slice in `modules` must have been produced by the Luau compiler matching
    /// this workspace's `rune-luau` VM.
    #[allow(unsafe_code)]
    pub const unsafe fn from_build_script(modules: &'static [PrecompiledEntry]) -> Self {
        Self { modules }
    }

    /// An empty precompiled table (all modules compile from source).
    pub const fn empty() -> Self {
        Self { modules: &[] }
    }
}

/// A plugin's files: a folder, or the copy built into the binary.
#[derive(Clone, Debug)]
pub enum Origin {
    /// A folder, with its files as they were read: what runs, and what a trust OK was for.
    Dir { dir: PathBuf, files: Arc<[(String, String)]> },
    /// Its files (no `locales/`) and its catalogs' table.
    Embedded(&'static [(&'static str, &'static str)], &'static [u8]),
}

/// A plugin folder, or why it doesn't read as one.
pub struct Found {
    pub manifest: Manifest,
    pub origin: Origin,
    pub tier: Tier,
    pub error: Option<String>,
    /// The SHA-256 of its files, when it asks for trust.
    pub hash: Option<String>,
}

/// The default parent `.luaurc` from `opencode-plugin-spec` (`plugins/.luaurc`).
pub fn default_luaurc() -> &'static str {
    opencode_plugin_spec::AUTHOR_FILES
        .iter()
        .find(|(p, _)| *p == ".luaurc")
        .map_or("", |(_, text)| *text)
}

/// Reads and checks a manifest against the contract this host implements.
pub fn parse(src: &str) -> Result<Manifest, String> {
    let m: Manifest = toml_edit::de::from_str(src).map_err(|e| e.message().to_owned())?;
    let id_ok = !m.id.is_empty()
        && m.id.len() <= 64
        && m.id.starts_with(|c: char| c.is_ascii_lowercase())
        && m.id.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if !id_ok {
        return Err(format!("`id` must be lowercase letters, digits and hyphens, starting with a letter (got {:?})", m.id));
    }
    let version = ContractVersion::parse(&m.contract).ok_or_else(|| format!("`contract` must be MAJOR.MINOR (got {:?})", m.contract))?;
    if ContractVersion::HOST.runs(version) == Compat::Unsupported {
        return Err(format!("targets contract {version}; this app implements {}", ContractVersion::HOST));
    }
    for path in std::iter::once(&m.entry).chain(&m.app) {
        if path.contains("..") || path.starts_with(['/', '\\']) {
            return Err(format!("{path:?} must be a path inside the plugin folder"));
        }
    }
    Ok(m)
}

/// Reads an embedded built-in plugin entry `(files, catalog_table)` into a [`Found`] descriptor.
pub fn read_embedded(files: &'static [(&'static str, &'static str)], catalogs: &'static [u8]) -> Option<Found> {
    let toml = files.iter().find(|(p, _)| *p == "plugin.toml")?.1;
    Some(match parse(toml) {
        Ok(manifest) => Found { manifest, origin: Origin::Embedded(files, catalogs), tier: Tier::Bundled, error: None, hash: None },
        Err(e) => Found {
            manifest: placeholder("embedded"),
            origin: Origin::Embedded(files, catalogs),
            tier: Tier::Bundled,
            error: Some(format!("plugin.toml: {e}")),
            hash: None,
        },
    })
}

/// Scans `dir` for plugin folders (or a single plugin folder when `tier == Tier::Dev`).
pub fn scan(tier: Tier, dir: &Path) -> Vec<Found> {
    if tier == Tier::Dev && dir.join("plugin.toml").is_file() {
        return read(tier, dir).into_iter().collect();
    }
    let Ok(entries) = std::fs::read_dir(dir) else { return Vec::new() };
    let mut dirs: Vec<PathBuf> = entries
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.join("plugin.toml").is_file())
        .collect();
    dirs.sort();
    dirs.iter().filter_map(|d| read(tier, d)).collect()
}

/// Reads a single plugin folder `dir` at `tier`.
pub fn read(tier: Tier, dir: &Path) -> Option<Found> {
    let files = read_files(dir);
    let src = files.iter().find(|(p, _)| p == "plugin.toml").map(|(_, t)| t.clone())?;
    let folder = dir.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let origin = Origin::Dir { dir: dir.to_owned(), files: files.into() };
    Some(match parse(&src) {
        Ok(manifest) => Found { manifest, origin, tier, error: None, hash: None },
        Err(e) => Found {
            manifest: placeholder(&folder),
            origin,
            tier,
            error: Some(format!("plugin.toml: {e}")),
            hash: None,
        },
    })
}

/// Message `key` of built-in `plugin_id` in `lang` from `builtins`, falling back to English.
pub fn builtin_message(builtins: &[BuiltinEntry<'_>], plugin_id: &str, lang: &str, key: &str) -> Option<&'static str> {
    let (_, _, bytes) = builtins.iter().find(|(id, _, _)| *id == plugin_id)?;
    let table = Catalogs::Table(bytes);
    match table.get(lang, key).or_else(|| table.get("en", key))? {
        std::borrow::Cow::Borrowed(s) => Some(s),
        std::borrow::Cow::Owned(_) => None,
    }
}

fn placeholder(id: &str) -> Manifest {
    let toml = format!("id = {id:?}\nname = {id:?}\nversion = \"0.0.0\"\ncontract = \"{}\"\n", ContractVersion::HOST);
    toml_edit::de::from_str(&toml).unwrap_or_else(|_| unreachable_manifest())
}

#[allow(clippy::panic)]
fn unreachable_manifest() -> Manifest {
    panic!("a fixed manifest always parses")
}

impl Origin {
    /// Only an embedded origin can contribute bytecode. A folder with the same id always
    /// supplies text; it cannot impersonate the built-in or send binary chunks to the VM.
    pub fn scripts_with(
        &self,
        files: &[(String, String)],
        folder: &str,
        entry: &str,
        precompiled: PrecompiledModules,
    ) -> rune_luau::Sources {
        self.scripts_with_luaurc(files, folder, entry, default_luaurc(), precompiled)
    }

    /// [`Origin::scripts_with`] with an explicit parent `.luaurc` string.
    pub fn scripts_with_luaurc(
        &self,
        files: &[(String, String)],
        folder: &str,
        entry: &str,
        parent_luaurc: &str,
        precompiled: PrecompiledModules,
    ) -> rune_luau::Sources {
        let mut sources = script_sources_with_luaurc(files, folder, entry, parent_luaurc);
        if let Self::Embedded(..) = self
            && let Some((_, modules)) = precompiled.modules.iter().find(|(id, _)| *id == folder)
        {
            for &(path, code, native) in *modules {
                #[allow(unsafe_code)]
                {
                    // SAFETY: `PrecompiledModules::from_build_script` requires the table to come
                    // from this VM's build-time compiler.
                    sources = unsafe { sources.with_embedded(path, code, native) };
                }
            }
        }
        sources
    }

    /// Every file, by its path relative to the plugin folder: a folder's as they were read, never
    /// read again.
    pub fn files(&self) -> Vec<(String, String)> {
        match self {
            Origin::Embedded(files, _) => files.iter().map(|(p, s)| ((*p).to_owned(), (*s).to_owned())).collect(),
            Origin::Dir { files, .. } => files.to_vec(),
        }
    }

    pub fn dir(&self) -> Option<&Path> {
        match self {
            Origin::Dir { dir, .. } => Some(dir),
            Origin::Embedded(..) => None,
        }
    }

    /// Its message catalogs: a built-in's table as it lies in the binary; a folder's from its
    /// `files`, each language parsed the first time a string is read in it.
    pub fn catalogs(&self, files: &[(String, String)]) -> Catalogs {
        match self {
            Origin::Embedded(_, table) => Catalogs::Table(table),
            Origin::Dir { .. } => Catalogs::folder(files),
        }
    }

    /// Where the plugin is, for people: its folder, or "Built into the app".
    pub fn describe(&self) -> String {
        self.dir().map_or_else(|| "Built into the app".to_owned(), |d| d.display().to_string())
    }
}

/// Plugin folder `dir`'s files, by their path relative to it, sorted. Reads the disk: never on the
/// app's thread.
pub fn read_files(dir: &Path) -> Vec<(String, String)> {
    let mut out = Vec::new();
    walk(dir, dir, &mut out);
    out.sort();
    out
}

fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    for path in std::fs::read_dir(dir).into_iter().flatten().flatten().map(|e| e.path()) {
        if path.is_dir() {
            walk(root, &path, out);
            continue;
        }
        if let Some(rel) = relative(root, &path)
            && kept(&rel)
            && let Ok(text) = std::fs::read_to_string(&path)
        {
            out.push((rel, text));
        }
    }
}

/// `path` under plugin folder `root`, `/`-separated.
pub fn relative(root: &Path, path: &Path) -> Option<String> {
    let rel: Vec<String> = path
        .strip_prefix(root)
        .ok()?
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect();
    Some(rel.join("/"))
}

/// Whether a plugin runs from the file at `rel`: its manifest, Luau modules, `.luaurc`,
/// `locales/*.json` catalogs (and `locales/fill/*.json`, see [`Catalogs`]) and `icons/*.svg` icons,
/// outside hidden folders.
pub fn kept(rel: &str) -> bool {
    let mut parts: Vec<&str> = rel.split('/').collect();
    let Some(name) = parts.pop() else { return false };
    if parts.iter().any(|d| d.starts_with('.')) {
        return false;
    }
    let under = |dir: &str, ext: &str| parts.last() == Some(&dir) && name.ends_with(ext);
    name.ends_with(".luau")
        || name == "plugin.toml"
        || name == ".luaurc"
        || under("locales", ".json")
        || (parts.ends_with(&["locales", "fill"]) && name.ends_with(".json"))
        || under("icons", ".svg")
}

/// Sanitizes and interns plugin `plugin`'s `icons/<name>.svg` files as its icons, replacing any
/// prior set for `plugin`. Returns rejected `(name, reason)` pairs for console diagnostics.
pub fn intern_icons(plugin: &str, files: &[(String, String)]) -> Vec<(String, String)> {
    let entries: Vec<(&str, &str)> = files
        .iter()
        .filter_map(|(path, svg)| {
            let name = path.strip_prefix("icons/")?.strip_suffix(".svg")?;
            (!name.is_empty() && !name.contains('/')).then_some((name, svg.as_str()))
        })
        .collect();
    crate::icons::replace_plugin(plugin, &entries)
}

/// The script sources of the half that starts at `entry`, with the plugins folder's default
/// `.luaurc` above them as editors see it.
pub fn script_sources(files: &[(String, String)], folder: &str, entry: &str) -> rune_luau::Sources {
    script_sources_with_luaurc(files, folder, entry, default_luaurc())
}

/// [`script_sources`] with an explicit parent `.luaurc` JSON string (skipped when empty).
pub fn script_sources_with_luaurc(files: &[(String, String)], folder: &str, entry: &str, parent_luaurc: &str) -> rune_luau::Sources {
    let sources = files
        .iter()
        .filter(|(p, _)| p.ends_with(".luau") || p.ends_with(".luaurc"))
        .fold(rune_luau::Sources::new(), |s, (p, text)| s.with(p, text.as_str()));
    let sources = if parent_luaurc.is_empty() { sources } else { sources.parent_config(parent_luaurc) };
    sources.folder(folder).entry(entry)
}

/// The SHA-256 of every file the plugin runs from: what trusting it means.
pub fn content_hash(files: &[(String, String)]) -> String {
    let mut h = Sha256::new();
    for (path, text) in files {
        h.update(path.as_bytes());
        h.update([0]);
        h.update(text.as_bytes());
        h.update([0]);
    }
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}
