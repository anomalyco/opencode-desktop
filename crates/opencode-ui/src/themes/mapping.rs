/// Desktop's V2 semantic colours for light or dark. The eight foreground inks
/// `mapV2Foreground` derives from the seed (`text-text-{base,muted,faint}`,
/// `icon-icon-{base,muted,faint,inverse,contrast}`) are not here, and neither are the
/// `blue-500`, `grey-300` and `grey-800` primitives, which come straight from the ramps. Every
/// value names one of those ramps or an alpha step, so the caller resolves it to a literal.
pub(super) fn semantics(dark: bool) -> super::Tokens {
    let table = if dark { DARK } else { LIGHT };
    table
        .iter()
        .map(|(key, value)| ((*key).to_owned(), (*value).to_owned()))
        .collect()
}
