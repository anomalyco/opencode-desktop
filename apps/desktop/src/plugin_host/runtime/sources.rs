//! Desktop plugin source discovery, embedded built-ins table, and `--plugin-dir` scanning,
//! delegating core origin/manifest/hashing primitives to `opencode_plugin_runtime::sources`.

pub use opencode_plugin_runtime::sources::{
    Found, Origin, PrecompiledModules, Tier, content_hash, intern_icons,
};

#[cfg(all(debug_assertions, not(disk_builtins)))]
use std::path::Path;
use std::path::PathBuf;

#[cfg(not(disk_builtins))]
mod embedded {
    include!(concat!(env!("OUT_DIR"), "/luau_builtins.rs"));
}

#[cfg(disk_builtins)]
mod disk {
    use std::path::Path;
    use std::sync::OnceLock;

    pub(super) fn root() -> &'static Path {
        Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../plugins"))
    }

    pub(super) fn luaurc() -> &'static str {
        static LUAURC: OnceLock<&'static str> = OnceLock::new();
        LUAURC.get_or_init(|| {
            std::fs::read_to_string(root().join(".luaurc"))
                .ok()
                .map(|s| &*Box::leak(s.into_boxed_str()))
                .unwrap_or_else(opencode_plugin_runtime::sources::default_luaurc)
        })
    }

    /// Built-in `(id, contributions)` scanned lazily from `plugins/` on disk, matching
    /// `apps/desktop/build.rs`'s `BUILTINS` and `CONTRIBUTIONS`.
    pub(super) fn index() -> &'static [(&'static str, &'static [&'static str])] {
        static INDEX: OnceLock<Vec<(&'static str, &'static [&'static str])>> = OnceLock::new();
        INDEX.get_or_init(|| {
            let mut dirs: Vec<_> = std::fs::read_dir(root()).into_iter().flatten().flatten().map(|e| e.path()).collect();
            dirs.sort();
            let mut out = Vec::new();
            for dir in dirs {
                if !dir.join("plugin.toml").is_file() {
                    continue;
                }
                let Some(name) = dir.file_name().map(|n| n.to_string_lossy().into_owned()) else { continue };
                let files = opencode_plugin_runtime::sources::read_files(&dir);
                let mut kinds: Vec<&'static str> = files
                    .iter()
                    .filter(|(rel, _)| rel.ends_with(".luau"))
                    .flat_map(|(_, src)| {
                        src.split("ctx:Add")
                            .skip(1)
                            .filter_map(|rest| rest.split_once('(').map(|(k, _)| k.to_owned()))
                            .collect::<Vec<_>>()
                    })
                    .filter(|k| !k.is_empty() && k.chars().all(char::is_alphanumeric))
                    .map(|k| &*Box::leak(k.into_boxed_str()))
                    .collect();
                kinds.sort_unstable();
                kinds.dedup();
                let id: &'static str = Box::leak(name.into_boxed_str());
                let kinds: &'static [&'static str] = Box::leak(kinds.into_boxed_slice());
                out.push((id, kinds));
            }
            out
        })
    }

    #[cfg(feature = "office")]
    pub(super) fn message(plugin_id: &str, lang: &str, key: &str) -> Option<&'static str> {
        use std::collections::HashMap;
        use std::sync::Mutex;
        type MessageCache = Mutex<HashMap<(String, String, String), Option<&'static str>>>;
        static CACHE: OnceLock<MessageCache> = OnceLock::new();
        let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
        let cache_key = (plugin_id.to_owned(), lang.to_owned(), key.to_owned());
        if let Ok(guard) = cache.lock()
            && let Some(&cached) = guard.get(&cache_key)
        {
            return cached;
        }
        let files = opencode_plugin_runtime::sources::read_files(&root().join(plugin_id));
        let catalogs = opencode_plugin_runtime::catalogs::Catalogs::folder(&files);
        let text = catalogs.get(lang, key).or_else(|| catalogs.get("en", key)).map(|s| {
            let leaked: &'static str = Box::leak(s.into_owned().into_boxed_str());
            leaked
        });
        if let Ok(mut guard) = cache.lock() {
            guard.insert(cache_key, text);
        }
        text
    }
}

pub fn parent_luaurc() -> &'static str {
    #[cfg(disk_builtins)]
    {
        disk::luaurc()
    }
    #[cfg(not(disk_builtins))]
    {
        embedded::LUAURC
    }
}

pub fn precompiled() -> PrecompiledModules {
    #[cfg(disk_builtins)]
    {
        PrecompiledModules::empty()
    }
    #[cfg(not(disk_builtins))]
    {
        // SAFETY: private static table generated by `apps/desktop/build.rs` with this VM's compiler.
        #[allow(unsafe_code)]
        unsafe {
            PrecompiledModules::from_build_script(embedded::MODULES)
        }
    }
}

pub fn scripts(origin: &Origin, files: &[(String, String)], folder: &str, entry: &str) -> rune_luau::Sources {
    origin.scripts_with_luaurc(files, folder, entry, parent_luaurc(), precompiled())
}

/// The built-ins: the copies built into the binary, after (in a debug build) the repository's
/// folders, so saving one reloads it. A release build reads no file here.
pub fn builtins() -> Vec<Found> {
    #[cfg(disk_builtins)]
    {
        opencode_plugin_runtime::sources::scan(Tier::Bundled, disk::root())
    }
    #[cfg(not(disk_builtins))]
    {
        let embedded = embedded::BUILTINS.iter().filter_map(|(_, files, catalogs)| opencode_plugin_runtime::sources::read_embedded(files, catalogs));
        #[cfg(debug_assertions)]
        let repo = opencode_plugin_runtime::sources::scan(Tier::Bundled, Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../plugins")));
        #[cfg(not(debug_assertions))]
        let repo = Vec::new();
        repo.into_iter().chain(embedded).collect()
    }
}

/// The plugins in folders, highest tier first: `--plugin-dir`, then the overrides, then the
/// installed ones; each that asks for trust with its files' SHA-256. Reads the disk, so it runs
/// off the app's thread.
pub fn folders() -> Vec<Found> {
    let mut tiers = Vec::new();
    if let Some(dir) = crate::arg("--plugin-dir") {
        tiers.push((Tier::Dev, PathBuf::from(dir)));
    }
    if let Some(config) = crate::dirs::config() {
        tiers.push((Tier::Override, config.join("plugins-override")));
    }
    if let Some(data) = crate::dirs::data() {
        tiers.push((Tier::User, data.join("plugins")));
    }
    let mut found: Vec<Found> = tiers.iter().flat_map(|(tier, dir)| opencode_plugin_runtime::sources::scan(*tier, dir)).collect();
    for f in found.iter_mut().filter(|f| f.tier.needs_trust()) {
        f.hash = Some(content_hash(&f.origin.files()));
    }
    found
}

/// What built-in `id` contributes (`Slot`, `Panel`, `ComposerPill`, ...: its `ctx:Add…` calls,
/// read at build time); empty for a plugin that isn't built in.
pub fn contributions(id: &str) -> &'static [&'static str] {
    #[cfg(disk_builtins)]
    {
        disk::index().iter().find(|(p, _)| *p == id).map_or(&[], |(_, kinds)| kinds)
    }
    #[cfg(not(disk_builtins))]
    {
        embedded::CONTRIBUTIONS.iter().find(|(p, _)| *p == id).map_or(&[], |(_, kinds)| kinds)
    }
}

/// What a built-in's record (`dormant`) is keyed by: the hash of the files this build carries for
/// it, or (a debug build, which runs them from the repository) of the files as read. None for a
/// plugin that isn't built in: those start as they always have.
pub fn files_hash(id: &str, origin: &Origin, tier: Tier) -> Option<String> {
    let base = match origin {
        #[cfg(not(disk_builtins))]
        Origin::Embedded(..) => embedded::HASHES.iter().find(|(p, _)| *p == id).map(|(_, h)| (*h).to_owned()),
        #[cfg(disk_builtins)]
        Origin::Embedded(..) => None,
        Origin::Dir { files, .. } if tier == Tier::Bundled => Some(content_hash(files)),
        Origin::Dir { .. } => None,
    }?;
    // The browser plugin registers its MCP tools only on builds with an engine, so an update that
    // adds or removes the engine source invalidates its dormant contribution record.
    #[cfg(not(target_arch = "wasm32"))]
    let engine_configured = browser_pane::BrowserHost::engine_configured();
    #[cfg(target_arch = "wasm32")]
    let engine_configured = false;
    if id == "browser" && !engine_configured {
        return Some(format!("{base}:no-engine"));
    }
    Some(base)
}

/// The ids of the built-ins this binary carries.
pub fn builtin_ids() -> impl Iterator<Item = &'static str> {
    #[cfg(disk_builtins)]
    {
        disk::index().iter().map(|(id, _)| *id)
    }
    #[cfg(not(disk_builtins))]
    {
        embedded::BUILTINS.iter().map(|(id, _, _)| *id)
    }
}

/// Message `key` of built-in `plugin_id` in `lang`, falling back to English.
#[cfg(feature = "office")]
pub fn builtin_message(plugin_id: &str, lang: &str, key: &str) -> Option<&'static str> {
    #[cfg(disk_builtins)]
    {
        disk::message(plugin_id, lang, key)
    }
    #[cfg(not(disk_builtins))]
    {
        opencode_plugin_runtime::sources::builtin_message(embedded::BUILTINS, plugin_id, lang, key)
    }
}
